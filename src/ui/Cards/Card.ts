  // Add method to start Card Placement Background animation
  public startCardPlacementBackgroundAnimation() {
    if (!this.cardPlacementBackground) return;

    this.cardPlacementBackground.alpha = 0.7;
    gsap.to(this.cardPlacementBackground, {
      alpha: 1,
      duration: 1,
      repeat: -1,
      yoyo: true,
      ease: "power1.inOut",
    });
  }

  // Add method to stop Card Placement Background animation
  public stopCardPlacementBackgroundAnimation() {
    if (this.cardPlacementBackground) {
      gsap.killTweensOf(this.cardPlacementBackground);
      this.cardPlacementBackground.alpha = 1;
    }
  }

  private isOverlaySet: boolean = false;

  public setOverlay(animate: boolean) {
    // * in case of bust this.card will be destroyed()
    if (this.width && !this.isOverlaySet) {
      this.overlay = new Graphics();
      this.overlay.roundRect(0, 0, 80, 120, 10);
      this.overlay.fill({
        color: 0x151515,
        alpha: 1,
      });

      this.overlay.alpha = 0;
      this.overlay.x = 0;
      this.overlay.y = 2.5;
      this.addChild(this.overlay);

      if (animate) {
        gsap.to(this.overlay, {
          alpha: 0.9,
          duration: 0.3,
        });
      } else {
        this.overlay.alpha = 0.9;
      }
      this.isOverlaySet = true;
    }
  }

  public removeOverlay() {
    if (!this.isOverlaySet || !this.overlay) return;

    const overlay = this.overlay;
    gsap.to(overlay, {
      alpha: 0,
      duration: 0.5,
      onComplete: () => {
        if (overlay && overlay.parent === this) {
          this.removeChild(overlay);
        }
        overlay.destroy();

        // Only reset if this was still the active overlay
        if (this.overlay === overlay) {
          this.overlay = null;
          this.isOverlaySet = false;
        }
      },
    });
  }

  public addCardClickIndexText(textValue: number) {
    if (this.cardClickIndexText) {
      this.removeChild(this.cardClickIndexText);
    }

    if (this.cardClickContainer && this.cardClickIndexBG) {
      this.cardClickIndexText = new Text({
        text: `${textValue}`,
        style: {
          fontSize: 20,
          fontFamily: "Inder",
          fill: 0xffe9a3,
          fontWeight: "900",
        },
      });
      this.cardClickIndexText.x =
        this.cardClickIndexBG.x +
        this.cardClickIndexBG.width / 2 -
        this.cardClickIndexText.width / 2;
      this.cardClickIndexText.y =
        this.cardClickIndexBG.y +
        this.cardClickIndexBG.height / 2 -
        this.cardClickIndexText.height / 2;
      this.cardClickContainer.addChild(this.cardClickIndexText);
    }
  }

  public changeCardValue(newCardId: CardId) {
    // Store current properties
    const currentX = this.x;
    const currentY = this.y;
    const currentScale = { x: this.scale.x, y: this.scale.y };
    const currentRotation = this.rotation;
    const currentAlpha = this.alpha;

    // Clear all children
    this.removeChildren();

    // Reset overlay state since children are cleared
    if (this.overlay) {
      this.overlay.destroy();
      this.overlay = null;
    }
    this.isOverlaySet = false;

    // Update cardId
    this.cardId = newCardId;

    // Recreate the card with new value using helper methods
    if (newCardId === "card-placement") {
      this.createCardPlacementCard();
    } else if (newCardId === "card-back") {
      this.createCardBackCard();
    } else if (newCardId !== null) {
      this.createRegularCard(newCardId);
    }

    // Restore properties
    this.x = currentX;
    this.y = currentY;
    this.scale.set(currentScale.x, currentScale.y);
    this.rotation = currentRotation;
    this.alpha = currentAlpha;
  }
